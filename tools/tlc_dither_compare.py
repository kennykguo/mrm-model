"""TLC dither-shape comparison on G26: every TLC experiment of the matrix with each dither arm.

    .venv/bin/python tools/tlc_dither_compare.py [--arms sine,sine_sampled,triangle] [--runs-dir runs/dither]
                                                 [--out docs/tlc/dither_compare.md]

An arm is a set of TLC controller params (faithful core): ``sine`` (the source default, 250 Hz-grid tone plan),
``sine_sampled`` (sine on the sampled tone plan: separates the plan from the shape), ``triangle`` / ``three`` /
``square`` (source B1 sampled shapes, ae9556b, on the sampled plan). Each experiment keeps its own params (cold
start, fault injection, ...) and gets the arm's params on top. The report rows come from tools/tlc_report.py.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARMS = {
    "sine": {},
    "sine_sampled": {"tone_plan": "sampled"},
    "triangle": {"dither_shape": "triangle"},
    "three": {"dither_shape": "three"},
    "square": {"dither_shape": "square"},
}
EXPERIMENTS = (
    "experiments/tlc/steady_tlc_faithful.yaml",
    "experiments/tlc/xpu_step_tlc.yaml",
    "experiments/tlc/a1_tlc.yaml",
    "experiments/tlc/a1_pd_adjacent_tlc.yaml",
    "experiments/tlc/laser_drift_tlc.yaml",
    "experiments/tlc/power_step_tlc.yaml",
    "experiments/tlc/squelch_tlc.yaml",
    "experiments/tlc/fallback_tlc.yaml",
    "experiments/tlc/cold_tlc.yaml",
    "experiments/tlc/cold_campaign_tlc.yaml",
    "experiments/tlc/ext_common_aggressor_tlc.yaml",
    "experiments/tlc/ext_kick_tlc.yaml",
    "experiments/tlc/ext_pd_fault_tlc.yaml",
)
COLS = ("peak_err_pm_max", "peak_err_pm_max_rings_1_up", "rms_err_pm_mean", "track_peak_err_pm_max",
        "rings_within_5pm", "unlocked_final", "wrong_line_final")


def _tool(name: str):
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def arm_overrides(arm: str) -> list[str]:
    if arm not in ARMS:
        raise ValueError(f"unknown arm {arm!r}; available: {sorted(ARMS)}")
    return [f"controller.params.{k}={v}" for k, v in ARMS[arm].items()]


def to_markdown(table: dict[str, dict[str, dict]], arms: list[str]) -> str:
    out = ["# TLC dither-shape comparison (G26)", "",
           "Generated by `tools/tlc_dither_compare.py`. Faithful core re-vendored at ECE496 `ae9556b`. Errors in pm, "
           "world 0, as in `docs/tlc/results.md` (`track_*`: dither tones removed). `sine`: 250 Hz-grid plan "
           "(4-13.5 kHz, 8 distinct tones); sampled arms: the source's four out_rate/N tones (3.8-7.1 kHz) repeated "
           "every four rings (`tone_plan.sampled_plan`); `sine_sampled` isolates the tone plan from the shape.", ""]
    for col in COLS:
        out += [f"## {col}", "", "| experiment | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
        for exp, row in table.items():
            cells = []
            for a in arms:
                v = row.get(a, {}).get(col)
                cells.append("—" if v is None else (f"{v:.3g}" if isinstance(v, float) else str(v)))
            out.append(f"| {exp} | " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--arms", default="sine,sine_sampled,triangle")
    ap.add_argument("--experiments", default="", help="comma-separated subset of the experiment paths")
    ap.add_argument("--runs-dir", default="runs/dither")
    ap.add_argument("--out", default="docs/tlc/dither_compare.md")
    args = ap.parse_args(argv)
    arms = [a for a in args.arms.split(",") if a]
    for a in arms:
        arm_overrides(a)                                   # fail fast on an unknown arm
    exps = [e for e in args.experiments.split(",") if e] or list(EXPERIMENTS)
    run_tool, report = _tool("tlc_run"), _tool("tlc_report")
    summaries, table = [], {}
    for exp in exps:
        for arm in arms:
            print(f"== {exp} :: {arm}", file=sys.stderr, flush=True)
            run = run_tool.run_with_telemetry(exp, f"{args.runs_dir}/{arm}", arm_overrides(arm), label={"arm": arm})
            s = {**report.summarize_run(run), "arm": arm}
            summaries.append(s)
            row = report.overview_rows([s])[0]
            table.setdefault(s["experiment"], {})[arm] = {**row, "campaign": s.get("campaign")}
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(to_markdown(table, arms))
    out.with_suffix(".json").write_text(json.dumps({"arms": {a: ARMS[a] for a in arms}, "runs": summaries,
                                                    "table": table}, indent=2, default=str))
    print(f"wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
