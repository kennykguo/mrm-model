"""Write site/js/colormaps.js: 256-step lookup tables of matplotlib's inferno (temperatures) and coolwarm
(the diverging lock-error and detuning scales), so the 3-D view and the 2-D plots share exact colours.

    .venv/bin/python webviz/make_colormaps.py
"""
from pathlib import Path

import matplotlib
from matplotlib import colormaps

OUT = Path(__file__).resolve().parent / "site" / "js" / "colormaps.js"


def lut(name, n=256):
    cm = colormaps[name]
    out = []
    for i in range(n):
        r, g, b, _ = cm(i / (n - 1))
        out.append("%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255)))
    return out


def main():
    lines = [f"// generated by webviz/make_colormaps.py from matplotlib {matplotlib.__version__}; do not edit",
             "// 256 sRGB steps each, as 6-digit hex strings without '#'."]
    for js_name, mpl_name in (("INFERNO", "inferno"), ("COOLWARM", "coolwarm")):
        hexes = lut(mpl_name)
        rows = [", ".join(f'"{h}"' for h in hexes[i:i + 12]) for i in range(0, len(hexes), 12)]
        lines.append(f"export const {js_name} = [\n  " + ",\n  ".join(rows) + "\n];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
