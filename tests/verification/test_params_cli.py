"""``mrm params ...`` on the subcommand registry (07 P2-12)."""
from pathlib import Path

import pytest

from mrm import cli

ROOT = Path(__file__).resolve().parents[2]
MINI = str(ROOT / "tests" / "data" / "mini.yaml")


def test_validate_ok(capsys):
    assert cli.main(["params", "validate", MINI, "--no-thermal-hook"]) == 0
    assert "mini.yaml: OK" in capsys.readouterr().out


def test_validate_fails_on_bad_override(capsys):
    assert cli.main(["params", "validate", MINI, "--set", "ring.optics.q_loaded=99999"]) == 1
    assert "FAILED" in capsys.readouterr().out


def test_show_explain_diff(capsys):
    assert cli.main(["params", "show", MINI]) == 0
    assert "ring.heater.p_fsr_mw = 25.45" in capsys.readouterr().out
    assert cli.main(["params", "explain", MINI, "ring.thermal.z_heater_ring_k_per_mw", "--no-thermal-hook"]) == 0
    assert "R2_heater_z" in capsys.readouterr().out
    assert cli.main(["params", "diff", MINI, MINI, "--alt-b", "uncertainty.thermo_optic=H86"]) == 0
    assert "alt=H86" in capsys.readouterr().out
    assert cli.main(["params", "show", MINI, "--set", "ring.heater.r_cold_ohms=1"]) == 1
    assert "r_cold_ohm" in capsys.readouterr().err


def test_table_out(tmp_path, capsys):
    out = tmp_path / "P.md"
    assert cli.main(["params", "table", MINI, "--out", str(out), "--no-thermal-hook"]) == 0
    assert out.read_text().startswith("# Parameters: `mini`")


def test_registry():
    cli._load_providers()
    assert "params" in cli.COMMANDS
    with pytest.raises(ValueError, match="twice"):
        cli.register("params", "dup", lambda p: None, lambda a: 0)
    ap = cli.build_parser()
    assert ap.prog == "mrm"


def test_parameters_md_is_current():
    """07 P2-12: docs/PARAMETERS.md is generated by `mrm params table g26`; fail when the committed file is stale."""
    doc = ROOT / "docs" / "PARAMETERS.md"
    preset = ROOT / "mrm" / "params" / "presets" / "g26.yaml"
    if not doc.exists() or not preset.exists():
        pytest.skip("docs/PARAMETERS.md or the g26 preset does not exist yet")
    from mrm.params import load
    from mrm.params.table import table
    assert doc.read_text() == table(load("g26")), "run: mrm params table g26 --out docs/PARAMETERS.md"


def test_format_doc_key_list_is_current():
    """The appendix of docs/PARAMETERS_FORMAT.md is `mrm params keys`; regenerate it after a schema change."""
    from mrm.params.table import keys_markdown
    text = (ROOT / "docs" / "PARAMETERS_FORMAT.md").read_text()
    a = text.index("<!-- keys:begin -->") + len("<!-- keys:begin -->")
    b = text.index("<!-- keys:end -->")
    assert text[a:b].strip() == keys_markdown().strip(), "regenerate the appendix with `mrm params keys`"


def test_keys_command(capsys):
    assert cli.main(["params", "keys"]) == 0
    assert "`ring.thermal.dlambda_dt_pm_per_k`" in capsys.readouterr().out


def test_realize_errors_exit_1_without_traceback(capsys):
    """A config that loads but cannot be realized (here R3 overdetermined) is an error message, not a traceback."""
    assert cli.main(["params", "table", MINI, "--set", "ring.geometry.radius_um=7.5", "--no-thermal-hook"]) == 1
    assert "OverdeterminedError" in capsys.readouterr().err
